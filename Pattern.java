import java.util.Scanner;
public class Pattern {
	public static void main(String[] args) {
		Scanner s=new Scanner(System.in);
			int n=s.nextInt();
			
			for (int i=1;i<=n;i++) {
				for(int c=1;c<=i;c++) {
						
					System.out.print("*");
				}
				System.out.println("");
					
				}
			
			}
		}
	
	


